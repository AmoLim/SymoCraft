"""Run OpenSpec at the docs planning root; refresh root skills via official update."""

import argparse
import os
from pathlib import Path
import shutil
import stat
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[2]
PLANNING_ROOT = ROOT / 'docs'


def cli_environment():
    return dict(os.environ, OPENSPEC_TELEMETRY='0', OPENSPEC_NO_UPDATE_CHECK='1',
                DO_NOT_TRACK='1', NO_COLOR='1')


def discover_cli(entry=None):
    if entry:
        result = Path(entry).resolve()
    else:
        npm = shutil.which('npm.cmd' if os.name == 'nt' else 'npm')
        if not npm:
            raise RuntimeError('npm unavailable; supply --cli-entry')
        lookup = subprocess.run([npm, 'root', '-g'], cwd=ROOT, env=cli_environment(),
                                capture_output=True, text=True, encoding='utf-8',
                                timeout=60, check=False)
        if lookup.returncode:
            raise RuntimeError(lookup.stderr)
        result = Path(lookup.stdout.strip()) / '@fission-ai/openspec/bin/openspec.js'
    if not result.is_file():
        raise RuntimeError('OpenSpec is not globally installed; supply --cli-entry')
    return result


def linked_path(path):
    if path.is_symlink():
        return True
    try:
        attributes = getattr(path.lstat(), 'st_file_attributes', 0)
    except FileNotFoundError:
        return False
    return bool(attributes & getattr(stat, 'FILE_ATTRIBUTE_REPARSE_POINT', 0x400))


def skill_files(directory):
    files = {}
    for parent in (directory, directory.parent):
        if linked_path(parent):
            raise RuntimeError(f'Refusing linked skill directory: {parent}')
    for skill in sorted(directory.glob('openspec-*')):
        if not skill.is_dir() or linked_path(skill):
            raise RuntimeError(f'Unexpected skill path: {skill}')
        for source in skill.rglob('*'):
            if linked_path(source):
                raise RuntimeError(f'Refusing linked skill file: {source}')
            if source.is_file():
                files[source.relative_to(directory)] = source
    marker = directory / '.openspec-target'
    if linked_path(marker):
        raise RuntimeError('Refusing linked skill marker')
    if marker.is_file():
        files[Path('.openspec-target')] = marker
    return files


def refresh_skills(command, arguments):
    if any(argument != '--force' for argument in arguments):
        raise RuntimeError('Project update accepts only --force; do not supply a target path')
    skills = ROOT / '.agents/skills'
    original = skill_files(skills)
    if not any(path.name == 'SKILL.md' for path in original):
        raise RuntimeError('No existing OpenSpec skills to refresh')
    snapshot = {path: source.read_bytes() for path, source in original.items()}
    # Official update couples planning and skill roots. Stage only its managed inputs,
    # then publish generated bytes without exposing the real specs or unrelated skills.
    with tempfile.TemporaryDirectory(prefix='symocraft-openspec-update-') as directory:
        staging = Path(directory)
        (staging / 'openspec').mkdir()
        shutil.copyfile(PLANNING_ROOT / 'openspec/config.yaml', staging / 'openspec/config.yaml')
        staged_skills = staging / '.agents/skills'
        for relative, source in original.items():
            target = staged_skills / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, target)
        env = cli_environment()
        if os.environ.get('XDG_CONFIG_HOME'):
            config_home = Path(os.environ['XDG_CONFIG_HOME'])
        elif os.name == 'nt':
            config_home = Path(os.environ.get('APPDATA') or Path.home() / 'AppData/Roaming')
        else:
            config_home = Path.home() / '.config'
        global_config = config_home / 'openspec/config.json'
        isolated_config = staging / 'config-home/openspec/config.json'
        if global_config.is_file():
            isolated_config.parent.mkdir(parents=True)
            shutil.copyfile(global_config, isolated_config)
        env['XDG_CONFIG_HOME'] = str(staging / 'config-home')
        result = subprocess.run([*command, 'update', *arguments], cwd=staging,
                                env=env, check=False)
        if result.returncode:
            return result.returncode
        generated = skill_files(staged_skills)
        if generated.keys() != original.keys():
            raise RuntimeError('Update adds/removes managed files; review the workflow set before publishing')
        generated_bytes = {path: source.read_bytes() for path, source in generated.items()}
        expected = dict(snapshot)

        def check_inputs():
            current = skill_files(skills)
            if current.keys() != original.keys() or any(
                    source.read_bytes() != expected[path] for path, source in current.items()):
                raise RuntimeError('Skills changed during update; refusing to overwrite concurrent edits')

        check_inputs()
        # These checks detect observed edits, not an atomic compare-and-swap or lock.
        for relative, content in generated_bytes.items():
            if content != snapshot[relative]:
                check_inputs()
                original[relative].write_bytes(content)
                expected[relative] = content
    return 0


def main():
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument('--cli-entry', type=Path)
    options, arguments = parser.parse_known_args()
    try:
        if not (PLANNING_ROOT / 'openspec/config.yaml').is_file():
            raise RuntimeError('Missing docs/openspec/config.yaml; refusing implicit initialization')
        if (ROOT / 'openspec').exists():
            raise RuntimeError('Duplicate root openspec directory; resolve ownership before continuing')
        node = shutil.which('node')
        if not node:
            raise RuntimeError('Node.js unavailable')
        command = [node, str(discover_cli(options.cli_entry))]
        if arguments and arguments[0] == 'init':
            raise RuntimeError('Already initialized; use the project update entry to refresh skills')
        if arguments and arguments[0] == 'update':
            return refresh_skills(command, arguments[1:])
        return subprocess.run([*command, *arguments], cwd=PLANNING_ROOT,
                              env=cli_environment(), check=False).returncode
    except (RuntimeError, OSError, subprocess.TimeoutExpired) as error:
        print(f'OpenSpec project entry: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    sys.exit(main())
